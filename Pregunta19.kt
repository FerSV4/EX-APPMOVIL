/*
19. Manipulación de Strings (5 puntos): Crea una función esPalindromo que reciba un
String y retorne true si es un palíndromo (se lee igual al derecho y al revés) o false si
no lo es. Ejemplo: "ana" → true, "hola" → false.
 */

esPalindromo(Palabra : String) : Boolean {
    val palabraformateada = Palabra.lowercase()
    return PalabraFormateada.Reversed()
}